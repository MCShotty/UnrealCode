import {_electron as electron} from 'playwright'
import {mkdtempSync,mkdirSync,writeFileSync} from 'node:fs'
import {tmpdir} from 'node:os'
import {join,resolve} from 'node:path'
import {execFileSync} from 'node:child_process'
import {createServer} from 'node:http'
import assert from 'node:assert/strict'

const root=mkdtempSync(join(tmpdir(),'unrealcode-git-browser-'))
const project=join(root,'plain-project'),profile=join(root,'profile')
mkdirSync(project)
writeFileSync(join(project,'hello.txt'),'A non-Git project remains editable.\n')
const packaged=process.argv.includes('--packaged')
const executablePath=resolve(process.env.UNREALCODE_QA_EXECUTABLE||(packaged?'dist/win-unpacked/UnrealCode.exe':'node_modules/electron/dist/electron.exe'))
const fixture=createServer((_request,response)=>{response.setHeader('Content-Type','text/html');response.end('<title>Browser fixture</title><main>Local browser fixture</main>')})
await new Promise(resolve=>fixture.listen(0,'127.0.0.1',resolve))
const fixtureUrl=`http://127.0.0.1:${fixture.address().port}/`
let app
try{
 app=await electron.launch({executablePath,args:packaged?[]:['.'],cwd:process.cwd(),env:{...process.env,UNREAL_DESKTOP_USER_DATA:profile,UNREAL_DESKTOP_BACKGROUND_CHECK:'1'}})
 const page=await app.firstWindow(),pageErrors=[]
 page.on('pageerror',error=>pageErrors.push(error.message))
 await page.getByRole('button',{name:'Set up later'}).click()
 await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0,checkboxChecked:false})})
 await page.evaluate(path=>window.unreal.openProject(path,true),project)
 await page.reload()
 await page.getByRole('button',{name:'Browser',exact:true}).waitFor({timeout:120000})
 await page.evaluate(()=>{window.__gitFixtureFailures=[];window.unreal.onFailure(value=>window.__gitFixtureFailures.push(value.code))})
 assert.deepEqual(await page.evaluate(async()=>({readiness:await window.unreal.gitAvailability(),changes:await window.unreal.gitChanges()})),{readiness:{available:false,code:'GIT_REPOSITORY_REQUIRED',message:'Agent team needs a Git repository. Open one at its root; no GitHub login is required.'},changes:null})
 await page.getByRole('button',{name:'Files',exact:true}).click()
 await page.getByRole('button',{name:/^Changes/}).click()
 await page.getByText(/Git changes are unavailable/).first().waitFor()
 await page.getByRole('button',{name:'GitHub',exact:true}).click()
 await page.getByText('This folder is not a Git repository.').first().waitFor()
 assert(await page.getByRole('button',{name:'Fetch'}).isDisabled())
 assert(await page.getByRole('button',{name:'Create draft PR'}).isDisabled())
 assert.equal(await page.getByText('Working tree is clean.').count(),0)
 const git=(...args)=>execFileSync('git',['-C',project,...args],{windowsHide:true,stdio:'ignore'})
 git('init')
 await page.getByRole('button',{name:'Refresh'}).click()
 await page.getByText('Make an initial commit before using worktrees and pull requests.').first().waitFor()
 await page.getByText('hello.txt').first().waitFor()
 assert.equal((await page.evaluate(()=>window.unreal.gitAvailability())).code,'GIT_COMMIT_REQUIRED')
 assert((await page.evaluate(()=>window.unreal.gitChanges())).includes('?? hello.txt'))
 await page.getByRole('button',{name:'Browser',exact:true}).click()
 await page.getByRole('heading',{name:'Open a page'}).waitFor()
 assert.equal(await page.getByRole('textbox',{name:'Browser address'}).inputValue(),'')
 await app.evaluate(({BrowserWindow})=>{const win=BrowserWindow.getAllWindows()[0];win.setMinimumSize(0,0);win.setContentSize(1200,800)})
 await page.screenshot({path:join(root,'browser-wide.png'),animations:'disabled'})
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'))
 await page.screenshot({path:join(root,'browser-wide-dark.png'),animations:'disabled'})
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','light'))
 await page.getByRole('button',{name:'New browser tab'}).click()
 assert(await page.getByRole('textbox',{name:'Browser address'}).evaluate(element=>element===document.activeElement))
 await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].setContentSize(640,560)})
 await page.waitForTimeout(300)
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Browser layout overflowed at compact width')
 const geometry=await page.evaluate(()=>{const names=['.shared-browser-page','.browser-shell','.shared-browser-viewport','.browser-welcome','.browser-welcome .primary-button'];return Object.fromEntries(names.map(name=>{const rect=document.querySelector(name).getBoundingClientRect();return [name,{top:rect.top,bottom:rect.bottom,height:rect.height}]}))})
 assert(geometry['.browser-welcome .primary-button'].bottom<=Math.min(geometry['.shared-browser-viewport'].bottom,geometry['.browser-shell'].bottom,geometry['.shared-browser-page'].bottom,560),`Compact browser action is clipped: ${JSON.stringify(geometry)}`)
 await page.screenshot({path:join(root,'browser-compact.png'),animations:'disabled'})
 await page.getByRole('textbox',{name:'Browser address'}).fill(fixtureUrl)
 await page.getByRole('textbox',{name:'Browser address'}).press('Enter')
 await page.getByRole('tab',{name:/Browser fixture/}).waitFor({timeout:15000})
 assert.equal(await page.getByRole('heading',{name:'Open a page'}).count(),0)
 await page.getByRole('button',{name:'Agent access'}).click()
 const dialog=page.getByRole('dialog',{name:'Agent browser access'})
 await dialog.waitFor()
 assert(await dialog.boundingBox().then(box=>box.x>=0&&box.x+box.width<=640))
 await dialog.getByRole('button',{name:'Cancel'}).click()
 assert.equal(await dialog.count(),0)
 assert(await page.getByRole('button',{name:'Agent access'}).evaluate(element=>element===document.activeElement))
 await page.getByRole('button',{name:'Agent access'}).click()
 await dialog.getByRole('checkbox',{name:'Allow agent access in this project'}).check()
 await dialog.getByRole('textbox',{name:/^Observe origins/}).fill(new URL(fixtureUrl).origin)
 await dialog.getByRole('button',{name:'Review and save grants'}).click()
 await page.waitForFunction(()=>!document.querySelector('.browser-access-dialog')?.hasAttribute('open'))
 const savedGrant=await page.evaluate(()=>window.unreal.sharedBrowserState().then(state=>state.grant))
 assert(savedGrant.enabled&&savedGrant.origins.includes(new URL(fixtureUrl).origin),'Agent origin grant did not save')
 await page.waitForFunction(()=>document.querySelector('.shared-browser-viewport')?.getBoundingClientRect().height>80)
 const attachedViews=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].contentView.children.length)
 assert(attachedViews>=1,'Live browser view did not remount after the access dialog closed')
 const browserText=await app.evaluate(async({BrowserWindow})=>BrowserWindow.getAllWindows()[0].contentView.children[0].webContents.executeJavaScript('document.body.innerText'))
 assert(browserText.includes('Local browser fixture'),'Live tab did not render its page content')
 await page.screenshot({path:join(root,'browser-active.png'),animations:'disabled'})
 const nativeCapture=await app.evaluate(async({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].capturePage()).toPNG().toString('base64'))
 writeFileSync(join(root,'browser-native.png'),Buffer.from(nativeCapture,'base64'))
 const failures=await page.evaluate(()=>window.__gitFixtureFailures)
 assert(!failures.some(code=>code.startsWith('GIT_')), `Unexpected Git failure notice: ${failures.join(', ')}`)
 assert.deepEqual(pageErrors,[])
 console.log(JSON.stringify({root,nonGitQuiet:true,initialCommitState:true,browserEmpty:true,compactNoOverflow:true,liveTab:true,grantDialog:true,attachedViews,geometry,pageErrors}))
}finally{await app?.close().catch(()=>{});await new Promise(resolve=>fixture.close(resolve))}
